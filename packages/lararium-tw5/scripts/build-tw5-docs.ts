/**
 * build-tw5-docs.ts — pack TiddlyWiki5's own native docs, two vendored wiki folders read whole, into the read-only TW5 docs
 * libraries (`src/tw5-docs.generated.ts`): the tw5.com edition (`TiddlyWiki5/editions/tw5.com/tiddlers`, `TW5_DOCS_PACK`) and the
 * dev edition (`TiddlyWiki5/editions/dev/tiddlers`, `TW5_DEV_PACK`). `tw5-docs-library` loads them on a face's first read of
 * `--recipe tw5-docs` or `--recipe tw5-dev`, or where the herm/hearth wiki stacks them (THE CANON FLOOR BY PLACE).
 *
 * ONE REVISION, TW5'S OWN READER. Each edition loads through TW5's own `loadTiddlersFromPath` (the `.tid` deserializer, `.meta`
 * sidecars, `.multids`, `tiddlywiki.files`) from the same submodule the core blob renders from (`build-tw5-vendor.ts`), so the
 * docs and the engine read one revision. The submodule takes no write: the pack lands in this package alone.
 *
 * WHAT THE PACK LEAVES OUT. Binary media (raster images, audio, PDF: base64 bytes no text read answers), JavaScript modules
 * (the edition's two demo modules: the docs engine runs no code the docs carry), and the edition's UI state (`$:/state/*`, the
 * splash screen `$:/SplashScreen`: a browser page's chrome, no doc). Every other record rides, sorted by title, so one revision
 * packs one byte string on any filesystem.
 *
 * WHERE IT RESTS. A code artifact (gitignored, beside `generated-tw5-version.ts`): never a bag, never a projection mirror, never
 * an ingest wave, never the genesis CAS. A face that never reads the docs never loads it.
 *
 * Usage: pnpm --filter @lararium/tw5 build (runs first), or tsx scripts/build-tw5-docs.ts alone.
 *
 * Meme: lar:///ha.ka.ba/lares/docs/pono/wiki-surface-scout
 */
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const OUT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "src", "tw5-docs.generated.ts");

/** A record the docs library carries no text read for: binary media and code. */
const LEFT_OUT = /^(image\/(?!svg)|audio\/|video\/|application\/pdf|application\/javascript)/;
/** A title that carries a browser page's UI state, never a doc. */
const UI_STATE = (title: string): boolean => title.startsWith("$:/state/") || title === "$:/SplashScreen";

const tw5Root = dirname(require.resolve("tiddlywiki/package.json"));
const tw = require("tiddlywiki").TiddlyWiki() as {
  boot: { argv: string[]; boot(callback: () => void): void };
  loadTiddlersFromPath(path: string): Array<{ tiddlers: Array<Record<string, unknown>> }>;
};
tw.boot.argv = [join(tw5Root, "editions", "empty")];
await new Promise<void>((resolve) => tw.boot.boot(resolve));

/** One edition's records, read whole through TW5's own loader, sorted by title. */
function packEdition(edition: string): Array<Record<string, string>> {
  const byTitle = new Map<string, Record<string, string>>();
  for (const file of tw.loadTiddlersFromPath(join(tw5Root, "editions", edition, "tiddlers"))) {
    for (const tiddler of file.tiddlers) {
      const type = typeof tiddler["type"] === "string" ? tiddler["type"] : "";
      if (LEFT_OUT.test(type) || tiddler["module-type"] !== undefined) continue;
      const fields: Record<string, string> = {};
      for (const name of Object.keys(tiddler).sort()) {
        const value = tiddler[name];
        if (value !== undefined && value !== null) fields[name] = String(value);
      }
      if (fields["title"] && !UI_STATE(fields["title"])) byTitle.set(fields["title"], fields);
    }
  }
  return [...byTitle.keys()].sort().map((title) => byTitle.get(title)!);
}

const docs = packEdition("tw5.com");
if (!docs.some((t) => t["title"] === "backlinks Operator")) throw new Error("build-tw5-docs: the tw5.com edition packed no `backlinks Operator`: read the submodule");
const dev = packEdition("dev");
if (dev.length === 0) throw new Error("build-tw5-docs: the dev edition packed no record: read the submodule");

writeFileSync(OUT, [
  "// GENERATED by scripts/build-tw5-docs.ts from TiddlyWiki5/editions/{tw5.com,dev}/tiddlers. Do not edit; re-run the build.",
  "/** The tw5.com edition's records, sorted by title, as one JSON array of field maps. */",
  `export const TW5_DOCS_PACK: string = ${JSON.stringify(JSON.stringify(docs))};`,
  "/** The dev edition's records, sorted by title, as one JSON array of field maps. */",
  `export const TW5_DEV_PACK: string = ${JSON.stringify(JSON.stringify(dev))};`,
  "",
].join("\n"), "utf-8");
console.log(`build-tw5-docs: packed ${docs.length} tw5.com records and ${dev.length} dev records → src/tw5-docs.generated.ts`);
