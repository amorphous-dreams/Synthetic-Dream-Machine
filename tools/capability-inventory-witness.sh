#!/bin/sh
# capability-inventory-witness — every island of both assemblies holds exactly the vessel doors the committed table
# names (tools/capability-inventory.json). It measures the BUILT tree: node islands through the real spawn
# functions around a worker_threads probe, web islands through the browser door code over a stand-in handle, and
# every call under packages/*/src that wraps or spawns an island or attaches it a door. A door a class reaches where
# the table says it did not, a new seam, or a seam that left reads red by name (tools/capability-inventory.mjs).
#
# A deliberate change re-writes the table in the commit that makes it: node tools/capability-inventory.mjs --write
set -eu
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
exec node "$HERE/capability-inventory.mjs"
