#!/bin/sh
# capability-inventory-witness — every island of both assemblies REACHES exactly the vessel doors the committed table
# names (tools/capability-inventory.json). The table measures reach, never a door's policy. It measures the BUILT
# tree: the node daemon through its spawn function and the node wiki and session islands through the pool's own host
# spawn, each against stand-in doors that grant and count every call; the web wiki and session islands through the
# browser pool's own host spawn over a stand-in Web Worker, reading every reply and the listeners the spawn attached;
# the web daemon reads `unmeasured`, since its spawn seam stands inside `openBrowserVessel`. A session island's view
# asks run through the pool core's own listener, which no row drives. Two source readings, each a multiset per file,
# hold the rest: every reference to a function that spawns, wraps or answers an island (raw worker constructors and
# renamed imports included), and every quoted ask or answer type. A door a class reaches where the table says it did
# not, a new or extra seam, a seam that left, or a new ask reads red by name (tools/capability-inventory.mjs).
#
# A deliberate change re-writes the table in the commit that makes it: node tools/capability-inventory.mjs --write
set -eu
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
exec node "$HERE/capability-inventory.mjs"
